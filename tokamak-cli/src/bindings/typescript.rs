//! The TypeScript module of a binding: classes, interfaces and unions whose
//! members call the generated native plugin.

use std::collections::HashSet;
use std::fmt::Write as _;

use super::model::{Availability, Callbacks, Kind, Member, Module, NamedKind, Param, Ty, Type};

/// Names a class's own members cannot take in JavaScript, which get a trailing `_`.
const RESERVED_MEMBERS: [&str; 1] = ["constructor"];
const RESERVED_STATICS: [&str; 6] = [
    "name",
    "length",
    "prototype",
    "caller",
    "arguments",
    "constructor",
];
const RESERVED_WORDS: [&str; 45] = [
    "arguments",
    "await",
    "break",
    "case",
    "catch",
    "class",
    "const",
    "continue",
    "debugger",
    "default",
    "delete",
    "do",
    "else",
    "enum",
    "eval",
    "export",
    "extends",
    "false",
    "finally",
    "for",
    "function",
    "if",
    "implements",
    "import",
    "in",
    "instanceof",
    "interface",
    "let",
    "new",
    "null",
    "package",
    "private",
    "protected",
    "public",
    "return",
    "static",
    "super",
    "switch",
    "this",
    "throw",
    "true",
    "try",
    "typeof",
    "var",
    "void",
];

pub(crate) fn emit(module: &Module) -> String {
    let mut out = String::new();
    let _ = writeln!(
        out,
        "// Generated by `tok bindings` from {}. Do not edit.",
        module.source
    );
    out.push_str("import { Bindings, NativeObject, type Classes, type TokamakContext } from \"@tokamakdev/plugin/bindings\";\n\n");
    let _ = writeln!(
        out,
        "const bindings = new Bindings({:?}, () => classes);",
        module.plugin
    );
    for ty in ordered(&module.types) {
        out.push('\n');
        emit_type(&mut out, ty);
    }
    for global in &module.globals {
        out.push('\n');
        emit_member(&mut out, global, Place::Module);
    }
    out.push_str("\nconst classes: Classes = {\n");
    for ty in module.types.iter().filter(|ty| is_object(&ty.kind)) {
        let _ = writeln!(out, "  {:?}: {},", ty.runtime, name(&ty.path));
    }
    out.push_str("};\n");
    out
}

fn is_object(kind: &Kind) -> bool {
    matches!(kind, Kind::Class { .. } | Kind::Protocol { .. })
}

/// The types, with each class after its superclass.
fn ordered(types: &[Type]) -> Vec<&Type> {
    let mut ordered: Vec<&Type> = Vec::new();
    let mut emitted: HashSet<&[String]> = HashSet::new();
    let bound: HashSet<&[String]> = types.iter().map(|ty| ty.path.as_slice()).collect();
    while ordered.len() < types.len() {
        let before = ordered.len();
        for ty in types {
            let ready = match &ty.kind {
                Kind::Class {
                    superclass: Some(superclass),
                    ..
                } => {
                    !bound.contains(superclass.as_slice())
                        || emitted.contains(superclass.as_slice())
                }
                _ => true,
            };
            if ready && emitted.insert(&ty.path) {
                ordered.push(ty);
            }
        }
        if ordered.len() == before {
            break;
        }
    }
    ordered
}

/// The TypeScript name of the type at `path`: nested names joined with `$`,
/// as the JVM names nested classes.
pub(crate) fn name(path: &[String]) -> String {
    path.join("$")
}

fn emit_type(out: &mut String, ty: &Type) {
    doc(out, "", &ty.availability);
    let name = name(&ty.path);
    if !is_object(&ty.kind) && !ty.members.is_empty() {
        emit_statics(out, ty, &name);
    }
    match &ty.kind {
        Kind::Alias(target) => {
            let _ = writeln!(out, "export type {name} = {};", ts(target));
        }
        Kind::Enum { cases } => {
            let _ = writeln!(
                out,
                "export type {name} = {};",
                union(cases.iter().map(|case| &case.name))
            );
        }
        Kind::Options { options } => {
            let _ = writeln!(
                out,
                "export type {name} = ({})[];",
                union(options.iter().map(|option| &option.name))
            );
        }
        Kind::Struct { fields, .. } => {
            let _ = writeln!(out, "export interface {name} {{");
            for field in fields {
                // A field newer than its struct is absent on older OS versions.
                let newer = field.availability.platforms != ty.availability.platforms;
                let _ = writeln!(
                    out,
                    "  {}{}: {};",
                    field.name,
                    if newer { "?" } else { "" },
                    ts(&field.ty)
                );
            }
            out.push_str("}\n");
        }
        Kind::Class {
            superclass,
            callbacks,
        } => {
            let parent = superclass
                .as_deref()
                .map_or_else(|| "NativeObject".to_owned(), self::name);
            emit_class(out, ty, &parent, callbacks.as_ref());
        }
        Kind::Protocol { callbacks } => emit_class(out, ty, "NativeObject", callbacks.as_ref()),
    }
}

/// The static members of a value type, as an object that shares its name.
fn emit_statics(out: &mut String, ty: &Type, name: &str) {
    let _ = writeln!(out, "export const {name} = {{");
    for (position, member) in ty.members.iter().enumerate() {
        if position > 0 {
            out.push('\n');
        }
        emit_member(out, member, Place::Object);
    }
    out.push_str("};\n\n");
    doc(out, "", &ty.availability);
}

fn union<'a>(names: impl Iterator<Item = &'a String>) -> String {
    let names: Vec<String> = names.map(|name| format!("{name:?}")).collect();
    if names.is_empty() {
        "never".to_owned()
    } else {
        names.join(" | ")
    }
}

fn emit_class(out: &mut String, ty: &Type, parent: &str, callbacks: Option<&Callbacks>) {
    let name = name(&ty.path);
    if let Some(callbacks) = callbacks {
        emit_handlers(out, &name, callbacks);
        doc(out, "", &ty.availability);
    }
    let _ = writeln!(out, "export class {name} extends {parent} {{");
    let mut first = true;
    let mut separate = |out: &mut String| {
        if !first {
            out.push('\n');
        }
        first = false;
    };
    for constant in &ty.constants {
        separate(out);
        doc(out, "  ", &constant.availability);
        let _ = writeln!(
            out,
            "  static readonly {} = {};",
            constant.name, constant.value
        );
    }
    if let Some(callbacks) = callbacks {
        separate(out);
        emit_implement(out, ty, &name, callbacks);
    }
    for overloads in overloads(&ty.members) {
        separate(out);
        match overloads.as_slice() {
            [member] => emit_member(out, member, Place::Class),
            overloads => emit_overloads(out, overloads),
        }
    }
    out.push_str("}\n");
}

/// The members, grouped by name, in the order each name first appears.
fn overloads(members: &[Member]) -> Vec<Vec<&Member>> {
    let mut groups: Vec<Vec<&Member>> = Vec::new();
    for member in members {
        let same = |group: &&mut Vec<&Member>| {
            group[0].name == member.name && group[0].is_static == member.is_static
        };
        match groups.iter_mut().find(same) {
            Some(group) => group.push(member),
            None => groups.push(vec![member]),
        }
    }
    groups
}

/// Members that share a name: TypeScript overload signatures, and one
/// method that calls the overload whose parameters the arguments fit.
fn emit_overloads(out: &mut String, overloads: &[&Member]) {
    let first = overloads[0];
    let (keyword, context, target) = if first.is_static {
        ("static ", "ctx: TokamakContext, ", "ctx")
    } else {
        ("", "", "this")
    };
    for member in overloads {
        doc(out, "  ", &member.availability);
        let _ = writeln!(
            out,
            "  {keyword}{}({context}{}): Promise<{}>;",
            first.name,
            params(&member.params),
            ts(&member.result)
        );
    }
    let _ = writeln!(
        out,
        "  {keyword}{}({context}...args: unknown[]): Promise<unknown> {{",
        first.name
    );
    let _ = writeln!(
        out,
        "    return bindings.call({target}, bindings.overload(args, ["
    );
    for member in overloads {
        let kinds: Vec<String> = member
            .params
            .iter()
            .map(|param| format!("[{}]", kinds(&param.ty).join(", ")))
            .collect();
        let _ = writeln!(out, "      [{:?}, [{}]],", member.key, kinds.join(", "));
    }
    out.push_str("    ]), args);\n  }\n");
}

/// What JavaScript values a parameter of `ty` takes, as `Bindings.overload` checks them.
fn kinds(ty: &Ty) -> Vec<String> {
    let kind = match ty {
        Ty::Optional(inner) => return [kinds(inner), vec!["\"null\"".to_owned()]].concat(),
        Ty::Named(named) => match &named.kind {
            NamedKind::Object => return vec![name(&named.path)],
            NamedKind::Alias(target) => return kinds(target),
            NamedKind::Enum => "string",
            NamedKind::Struct => "object",
            NamedKind::Options => "array",
        },
        Ty::Bool => "boolean",
        Ty::Int(_) | Ty::Float(_) | Ty::Number(_) => "number",
        Ty::Char | Ty::String(_) => "string",
        Ty::Bytes => "bytes",
        Ty::Date => "date",
        Ty::List(..) => "array",
        Ty::Record(_) => "object",
        Ty::Any | Ty::Void | Ty::Error => "any",
    };
    vec![format!("{kind:?}")]
}

fn emit_handlers(out: &mut String, name: &str, callbacks: &Callbacks) {
    let _ = writeln!(out, "export interface {name}Methods {{");
    for method in &callbacks.methods {
        doc(out, "  ", &method.availability);
        let _ = writeln!(
            out,
            "  {}?({}): void | Promise<void>;",
            method.name,
            params(&method.params)
        );
    }
    out.push_str("}\n\n");
}

fn emit_implement(out: &mut String, ty: &Type, name: &str, callbacks: &Callbacks) {
    let methods: Vec<String> = callbacks
        .methods
        .iter()
        .map(|method| format!("{:?}", method.name))
        .collect();
    out.push_str("  /** A native object whose methods call `handlers`. */\n");
    let _ = writeln!(
        out,
        "  static implement(ctx: TokamakContext, handlers: {name}Methods): Promise<{name}> {{\n    return bindings.implement(ctx, {name}, {:?}, [{}], handlers);\n  }}",
        ty.name(),
        methods.join(", "),
    );
}

/// Where a member is declared.
#[derive(Clone, Copy, PartialEq, Eq)]
enum Place {
    /// A class's method.
    Class,
    /// A method of the object holding a value type's static members.
    Object,
    /// A module function, for a global.
    Module,
}

fn emit_member(out: &mut String, member: &Member, place: Place) {
    let indent = if place == Place::Module { "" } else { "  " };
    doc(out, indent, &member.availability);
    let reserved: &[&str] = match place {
        Place::Class if member.is_static => &RESERVED_STATICS,
        Place::Class => &RESERVED_MEMBERS,
        Place::Object | Place::Module => &[],
    };
    let mut name = member.name.clone();
    if reserved.contains(&name.as_str()) {
        name.push('_');
    }
    let mut parameters = Vec::new();
    if member.is_static {
        parameters.push("ctx: TokamakContext".to_owned());
    }
    if !member.params.is_empty() {
        parameters.push(params(&member.params));
    }
    // An asynchronous member's task stops when its signal aborts.
    let cancellable = member.effects.asynchronous && !member.stream;
    if cancellable {
        parameters.push("options?: { signal?: AbortSignal }".to_owned());
    }
    let result = ts(&member.result);
    let (returns, call) = if member.stream {
        (format!("ReadableStream<{result}>"), "stream")
    } else {
        (format!("Promise<{result}>"), "call")
    };
    let target = if member.is_static { "ctx" } else { "this" };
    let arguments: Vec<String> = member
        .params
        .iter()
        .map(|param| safe(&param.name))
        .collect();
    let signal = if cancellable { ", options?.signal" } else { "" };
    let (keyword, end) = match place {
        Place::Module => ("export function ", ""),
        Place::Class if member.is_static => ("static ", ""),
        Place::Class => ("", ""),
        Place::Object => ("", ","),
    };
    let _ = writeln!(
        out,
        "{indent}{keyword}{name}({}): {returns} {{\n{indent}  return bindings.{call}({target}, {:?}, [{}]{signal});\n{indent}}}{end}",
        parameters.join(", "),
        member.key,
        arguments.join(", "),
    );
}

fn params(params: &[Param]) -> String {
    params
        .iter()
        .map(|param| format!("{}: {}", safe(&param.name), ts(&param.ty)))
        .collect::<Vec<_>>()
        .join(", ")
}

/// `name` as a JavaScript parameter: reserved words get a trailing `_`.
fn safe(name: &str) -> String {
    let name = name.trim_matches('`');
    if RESERVED_WORDS.contains(&name) {
        format!("{name}_")
    } else {
        name.to_owned()
    }
}

pub(crate) fn ts(ty: &Ty) -> String {
    match ty {
        Ty::Void => "void".to_owned(),
        Ty::Bool => "boolean".to_owned(),
        Ty::Int(_) | Ty::Float(_) | Ty::Number(_) => "number".to_owned(),
        Ty::Char | Ty::String(_) => "string".to_owned(),
        Ty::Date => "Date".to_owned(),
        Ty::Bytes => "Uint8Array".to_owned(),
        Ty::Error => "DOMException".to_owned(),
        Ty::Any => "unknown".to_owned(),
        Ty::Optional(inner) => format!("{} | null", ts(inner)),
        Ty::List(element, _) => {
            let element = ts(element);
            if element.contains(' ') {
                format!("({element})[]")
            } else {
                format!("{element}[]")
            }
        }
        Ty::Record(value) => format!("Record<string, {}>", ts(value)),
        Ty::Named(named) => name(&named.path),
    }
}

/// The doc comment listing where a symbol is available.
fn doc(out: &mut String, indent: &str, availability: &Availability) {
    let platforms: Vec<String> = availability
        .platforms
        .iter()
        .map(|(platform, version)| match version {
            Some(version) => format!("{platform} {version}+"),
            None => platform.clone(),
        })
        .collect();
    let mut lines = vec![platforms.join(", ")];
    if let Some(message) = &availability.deprecated {
        lines.push(format!("@deprecated {message}").trim_end().to_owned());
    }
    if lines.len() == 1 {
        let _ = writeln!(out, "{indent}/** {} */", lines[0]);
        return;
    }
    let _ = writeln!(out, "{indent}/**");
    for line in lines {
        let _ = writeln!(out, "{indent} * {line}");
    }
    let _ = writeln!(out, "{indent} */");
}
