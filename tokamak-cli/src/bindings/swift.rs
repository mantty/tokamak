//! The Swift native plugin of an Apple binding: one class whose cases
//! perform each bound call, with conversions for the module's value types
//! and implementations of its protocols.

use std::fmt::Write as _;

use super::model::{
    Availability, Callback, Case, Collection, Field, Kind, Member, MemberKind, Module, NamedKind,
    Ty, Type,
};

/// The Swift class of the plugin `id`'s bindings, which the Apple pack registers.
pub(crate) fn class_name(id: &str) -> String {
    format!("TokamakBindings_{}", id.replace('-', "_"))
}

pub(crate) fn emit(module: &Module, id: &str) -> String {
    let class = class_name(id);
    let mut out = String::new();
    let _ = writeln!(
        out,
        "// Generated by `tok bindings` from {}. Do not edit.\n",
        module.source
    );
    for import in std::iter::once("Foundation").chain(module.imports.iter().map(String::as_str)) {
        let _ = writeln!(out, "import {import}");
    }
    // The bindings call deprecated APIs on purpose, so their warnings are noise.
    let _ = writeln!(
        out,
        "\n#if hasAttribute(diagnose)\n  @diagnose(DeprecatedDeclaration, as: ignored)\n#endif\nfinal class {class}: TokamakPlugin {{\n  let id = {:?}\n  private let host: TokamakHost\n\n  init(host: TokamakHost) {{ self.host = host }}",
        module.plugin
    );
    let emitter = Emitter { class: &class };
    emitter.calls(&mut out, module);
    emitter.subscriptions(&mut out, module);
    for ty in &module.types {
        emitter.conversions(&mut out, ty);
        if let Some(callbacks) = ty.callbacks() {
            emitter.implementation(&mut out, ty, callbacks);
        }
    }
    out.push_str("}\n");
    out
}

/// The members the module calls, with the type each belongs to.
fn members(module: &Module) -> impl Iterator<Item = (Option<&Type>, &Member)> {
    module
        .types
        .iter()
        .flat_map(|ty| ty.members.iter().map(move |member| (Some(ty), member)))
        .chain(module.globals.iter().map(|member| (None, member)))
}

/// The end of a request switch: the rejection of a member the plugin does not bind.
const UNBOUND: &str = "    default:\n      throw .notSupported(\"\\(method) is not supported\")\n    }\n  }\n";

struct Emitter<'a> {
    class: &'a str,
}

impl Emitter<'_> {
    fn calls(&self, out: &mut String, module: &Module) {
        out.push_str(
            "\n  func callBytes(method: String, payload: Data, reply: @escaping TokamakPluginBytesReply)\n    throws(TokamakPluginError) -> (() -> Void)?\n  {\n    let b = try TokamakBinding(payload, resources: host.resources, reply: reply)\n    switch method {\n",
        );
        for (owner, member) in members(module).filter(|(_, member)| !member.stream) {
            within_os(
                out,
                os_condition(&member.availability).as_deref(),
                "    ",
                |out| {
                    let _ = writeln!(out, "    case {:?}:", member.key);
                    if let Some(versions) = versions(&member.availability) {
                        let _ = writeln!(
                            out,
                            "      guard #available({versions}, *) else {{ throw TokamakBinding.unavailable }}"
                        );
                    }
                    let run = if member.effects.asynchronous {
                        "task"
                    } else {
                        "run"
                    };
                    let _ = writeln!(
                        out,
                        "      return b.{run} {{ {} }}",
                        self.body(owner, member)
                    );
                },
            );
        }
        out.push_str(UNBOUND);
    }

    fn subscriptions(&self, out: &mut String, module: &Module) {
        out.push_str(
            "\n  func subscribeBytes(method: String, payload: Data, reply: @escaping TokamakPluginBytesReply)\n    throws(TokamakPluginError) -> () -> Void\n  {\n    let b = try TokamakBinding(payload, resources: host.resources, reply: reply)\n    switch method {\n",
        );
        for ty in &module.types {
            if ty.callbacks().is_some() {
                subscription_case(
                    out,
                    &ty.name(),
                    &ty.availability,
                    &format!("b.implement({}Implementation.self)", flat(ty)),
                );
            }
        }
        for (owner, member) in members(module).filter(|(_, member)| member.stream) {
            let sequence = self.call(owner, member);
            let body = format!(
                "b.stream({{ {sequence} }}, encode: {{ {} }})",
                self.encode(&member.result, "$0")
            );
            subscription_case(out, &member.key, &member.availability, &body);
        }
        out.push_str(UNBOUND);
    }

    /// The statements that perform `member` and return its encoded result.
    fn body(&self, owner: Option<&Type>, member: &Member) -> String {
        let call = self.call(owner, member);
        // An out-error the call sets rejects it.
        let (declare, check) = if member.params.iter().any(|param| param.ty == Ty::OutError) {
            ("var error: NSError?; ", "; if let error { throw error }")
        } else {
            ("", "")
        };
        if member.result == Ty::Void {
            return format!("{declare}{call}{check}; return nil");
        }
        format!(
            "{declare}let value = {call}{check}; return {}",
            self.encode(&member.result, "value")
        )
    }

    /// The expression that performs `member`, with `try` and `await` as it needs.
    fn call(&self, owner: Option<&Type>, member: &Member) -> String {
        let target = match owner {
            None => String::new(),
            Some(owner) if member.is_static => format!("{}.", owner.native),
            Some(owner) => format!("b.target({}.self).", native_type(owner)),
        };
        let arguments = || {
            let mut index = 0;
            member
                .params
                .iter()
                .zip(member.labels.iter().chain(std::iter::repeat(&None)))
                .map(|(param, label)| {
                    let value = if param.ty == Ty::OutError {
                        "&error".to_owned()
                    } else {
                        index += 1;
                        self.decode(&param.ty, &format!("b[{}]", index - 1))
                    };
                    label
                        .as_ref()
                        .map_or(value.clone(), |label| format!("{label}: {value}"))
                })
                .collect::<Vec<_>>()
                .join(", ")
        };
        let expression = match member.kind {
            MemberKind::Initializer => format!(
                "{}({})",
                owner.map_or("", |owner| owner.native.as_str()),
                arguments()
            ),
            MemberKind::Method => format!("{target}{}({})", member.native, arguments()),
            MemberKind::Getter => format!("{target}{}", member.native),
            MemberKind::Setter => format!(
                "{target}{} = {}",
                member.native,
                self.decode(&member.params[0].ty, "b[0]")
            ),
        };
        let throws = member.effects.throws
            || !member.params.is_empty()
            || (owner.is_some() && !member.is_static);
        let effects = match (throws, member.effects.asynchronous) {
            (true, true) => "try await ",
            (true, false) => "try ",
            (false, true) => "await ",
            (false, false) => "",
        };
        format!("{effects}{expression}")
    }

    /// The expression decoding the JSON `value` as `ty`, which throws.
    fn decode(&self, ty: &Ty, value: &str) -> String {
        let class = self.class;
        match ty {
            Ty::Optional(inner) => {
                format!("b.optional({value}) {{ try {} }}", self.decode(inner, "$0"))
            }
            Ty::List(element, collection) => {
                let array = format!("b.array({value}) {{ try {} }}", self.decode(element, "$0"));
                if *collection == Collection::Set {
                    format!("Set({array})")
                } else {
                    array
                }
            }
            Ty::Record(inner) => {
                format!("b.record({value}) {{ try {} }}", self.decode(inner, "$0"))
            }
            Ty::Named(named) => match &named.kind {
                NamedKind::Object => format!(
                    "b.object({value}, as: {}.self)",
                    parenthesized(&named.native)
                ),
                NamedKind::Alias(target) => self.decode(target, value),
                _ => format!("{class}.decode({value}, b, as: {}.self)", named.native),
            },
            scalar => format!("b.decode({value}, as: {}.self)", scalar_type(scalar)),
        }
    }

    /// The expression encoding the native `value` of `ty` as JSON.
    fn encode(&self, ty: &Ty, value: &str) -> String {
        let class = self.class;
        match ty {
            Ty::Optional(inner) => format!(
                "b.encode(optional: {value}) {{ {} }}",
                self.encode(inner, "$0")
            ),
            Ty::List(element, _) => format!(
                "b.encode(array: {value}) {{ {} }}",
                self.encode(element, "$0")
            ),
            Ty::Record(inner) => format!(
                "b.encode(record: {value}) {{ {} }}",
                self.encode(inner, "$0")
            ),
            Ty::Named(named) => match &named.kind {
                NamedKind::Object => format!("b.encode(object: {value})"),
                NamedKind::Alias(target) => self.encode(target, value),
                _ => format!("{class}.encode({value}, b)"),
            },
            _ => format!("b.encode({value})"),
        }
    }

    /// The static conversions of an enum, option set or struct.
    fn conversions(&self, out: &mut String, ty: &Type) {
        let (encode, decode) = match &ty.kind {
            Kind::Enum { cases } => (encode_enum(ty, cases), decode_enum(ty, cases)),
            Kind::Options { options } => (encode_options(ty, options), decode_options(ty, options)),
            Kind::Struct {
                fields,
                constructible,
            } => (
                self.encode_struct(ty, fields),
                constructible
                    .then(|| self.decode_struct(ty, fields))
                    .unwrap_or_default(),
            ),
            _ => return,
        };
        within_os(
            out,
            os_condition(&ty.availability).as_deref(),
            "  ",
            |out| {
                let available = versions(&ty.availability)
                    .map(|versions| format!("  @available({versions}, *)\n"))
                    .unwrap_or_default();
                let native = &ty.native;
                let _ = write!(
                    out,
                    "\n{available}  private static func encode(_ value: {native}, _ b: TokamakBinding) -> Any {{\n{encode}  }}\n"
                );
                if !decode.is_empty() {
                    let _ = write!(
                        out,
                        "\n{available}  private static func decode(_ value: Any, _ b: TokamakBinding, as type: {native}.Type) throws -> {native} {{\n{decode}  }}\n"
                    );
                }
            },
        );
    }

    fn encode_struct(&self, ty: &Type, fields: &[Field]) -> String {
        let mut body = "    var fields: [String: Any] = [:]\n".to_owned();
        for field in fields {
            with_os(&mut body, &field.availability, &ty.availability, |body| {
                let value = self.encode(&field.ty, &format!("value.{}", field.name));
                match newer(&field.availability, &ty.availability) {
                    Some(versions) => {
                        let _ = writeln!(
                            body,
                            "    if #available({versions}, *) {{ fields[{:?}] = {value} }}",
                            field.name
                        );
                    }
                    None => {
                        let _ = writeln!(body, "    fields[{:?}] = {value}", field.name);
                    }
                }
            });
        }
        body.push_str("    return fields\n");
        body
    }

    fn decode_struct(&self, ty: &Type, fields: &[Field]) -> String {
        let arguments: Vec<String> = fields
            .iter()
            .map(|field| {
                format!(
                    "      {}: {}",
                    field.name,
                    self.decode(&field.ty, &format!("b.field(value, {:?})", field.name))
                )
            })
            .collect();
        format!("    try {}(\n{}\n    )\n", ty.native, arguments.join(",\n"))
    }

    /// The class that implements a protocol, or subclasses a class, for JavaScript handlers.
    fn implementation(&self, out: &mut String, ty: &Type, callbacks: &[Callback]) {
        within_os(
            out,
            os_condition(&ty.availability).as_deref(),
            "  ",
            |out| {
                let available = versions(&ty.availability)
                    .map(|versions| format!("  @available({versions}, *)\n"))
                    .unwrap_or_default();
                let _ = writeln!(
                    out,
                    "\n{available}  private final class {}Implementation: TokamakBindingImplementation, {} {{",
                    flat(ty),
                    ty.native
                );
                if callbacks.iter().any(|method| method.selector.is_some()) {
                    out.push_str(
                        "    override class var selectors: [Selector: String] {\n      [\n",
                    );
                    for method in callbacks {
                        if let Some(selector) = &method.selector {
                            let _ = writeln!(
                                out,
                                "        NSSelectorFromString({selector:?}): {:?},",
                                method.name
                            );
                        }
                    }
                    out.push_str("      ]\n    }\n");
                }
                for method in callbacks {
                    self.callback(out, ty, method);
                }
                out.push_str("  }\n");
            },
        );
    }

    fn callback(&self, out: &mut String, ty: &Type, method: &Callback) {
        let arguments: Vec<String> = method
            .params
            .iter()
            .map(|param| self.encode(&param.ty, &param.name))
            .collect();
        with_os(out, &method.availability, &ty.availability, |out| {
            if let Some(versions) = versions(&method.availability) {
                let _ = writeln!(out, "\n    @available({versions}, *)");
            } else {
                out.push('\n');
            }
            let _ = writeln!(
                out,
                "    {} {{\n      call({:?}) {{ b in [{}] }}\n    }}",
                method.declaration,
                method.name,
                arguments.join(", ")
            );
        });
    }
}

fn subscription_case(out: &mut String, key: &str, availability: &Availability, body: &str) {
    within_os(out, os_condition(availability).as_deref(), "    ", |out| {
        let _ = writeln!(out, "    case {key:?}:");
        if let Some(versions) = versions(availability) {
            let _ = writeln!(
                out,
                "      guard #available({versions}, *) else {{ throw TokamakBinding.unavailable }}"
            );
        }
        let _ = writeln!(out, "      return {body}");
    });
}

fn encode_enum(ty: &Type, cases: &[Case]) -> String {
    let mut body = String::new();
    for case in cases {
        with_os(&mut body, &case.availability, &ty.availability, |body| {
            let condition = newer(&case.availability, &ty.availability)
                .map(|versions| format!("#available({versions}, *), "))
                .unwrap_or_default();
            let _ = writeln!(
                body,
                "    if {condition}value == .{} {{ return {:?} }}",
                case.native, case.name
            );
        });
    }
    body.push_str("    return \"\\(value)\"\n");
    body
}

fn decode_enum(ty: &Type, cases: &[Case]) -> String {
    let mut body = "    switch try b.decode(value, as: String.self) {\n".to_owned();
    for case in cases {
        with_os(&mut body, &case.availability, &ty.availability, |body| {
            let _ = writeln!(body, "    case {:?}:", case.name);
            newer_guard(body, &case.availability, &ty.availability, "      ");
            let _ = writeln!(body, "      return .{}", case.native);
        });
    }
    body.push_str("    default: throw b.mismatch(value, type)\n    }\n");
    body
}

fn encode_options(ty: &Type, options: &[Case]) -> String {
    let mut body = "    var names: [String] = []\n".to_owned();
    for option in options {
        with_os(&mut body, &option.availability, &ty.availability, |body| {
            let _ = writeln!(
                body,
                "    if value.contains(.{}) {{ names.append({:?}) }}",
                option.native, option.name
            );
        });
    }
    body.push_str("    return names\n");
    body
}

fn decode_options(ty: &Type, options: &[Case]) -> String {
    let mut body = format!(
        "    var options: {} = []\n    for name in try b.array(value, {{ try b.decode($0, as: String.self) }}) {{\n      switch name {{\n",
        ty.native
    );
    for option in options {
        with_os(&mut body, &option.availability, &ty.availability, |body| {
            let _ = writeln!(body, "      case {:?}:", option.name);
            newer_guard(body, &option.availability, &ty.availability, "        ");
            let _ = writeln!(body, "        options.insert(.{})", option.native);
        });
    }
    body.push_str(
        "      default: throw b.mismatch(name, type)\n      }\n    }\n    return options\n",
    );
    body
}

/// The Swift type an instance member is called on.
fn native_type(owner: &Type) -> String {
    match owner.kind {
        Kind::Protocol { .. } => format!("(any {})", owner.native),
        _ => owner.native.clone(),
    }
}

fn parenthesized(native: &str) -> String {
    if native.starts_with("any ") {
        format!("({native})")
    } else {
        native.to_owned()
    }
}

/// The type's name as one identifier.
fn flat(ty: &Type) -> String {
    ty.path.join("_")
}

fn scalar_type(ty: &Ty) -> &str {
    match ty {
        Ty::Bool => "Bool",
        Ty::Int(native) | Ty::Float(native) | Ty::String(native) | Ty::Number(native) => native,
        Ty::Date => "Date",
        Ty::Bytes => "Data",
        _ => "Any",
    }
}

/// The `#if` condition of a symbol that is on one platform only.
fn os_condition(availability: &Availability) -> Option<String> {
    match availability.platforms.as_slice() {
        [(platform, _)] => Some(format!("os({platform})")),
        _ => None,
    }
}

/// The `#available` platforms and versions of a symbol, when any has a version.
fn versions(availability: &Availability) -> Option<String> {
    let versions: Vec<String> = availability
        .platforms
        .iter()
        .filter_map(|(platform, version)| Some(format!("{platform} {}", version.as_ref()?)))
        .collect();
    (!versions.is_empty()).then(|| versions.join(", "))
}

/// Writes `write`'s output, within `#if condition` when there is one.
fn within_os(
    out: &mut String,
    condition: Option<&str>,
    indent: &str,
    write: impl FnOnce(&mut String),
) {
    if let Some(condition) = condition {
        let _ = writeln!(out, "{indent}#if {condition}");
    }
    write(out);
    if condition.is_some() {
        let _ = writeln!(out, "{indent}#endif");
    }
}

/// Writes `write`'s output, within `#if` when the symbol is on fewer
/// platforms than its type.
fn with_os(
    out: &mut String,
    availability: &Availability,
    parent: &Availability,
    write: impl FnOnce(&mut String),
) {
    let condition = (availability.platforms.len() < parent.platforms.len())
        .then(|| os_condition(availability))
        .flatten();
    within_os(out, condition.as_deref(), "    ", write);
}

/// Rejects a value introduced after its type on the running OS version.
fn newer_guard(out: &mut String, availability: &Availability, parent: &Availability, indent: &str) {
    if let Some(versions) = newer(availability, parent) {
        let _ = writeln!(
            out,
            "{indent}guard #available({versions}, *) else {{ throw TokamakBinding.unavailable }}"
        );
    }
}

/// The `#available` versions of a symbol introduced after its `parent`.
fn newer(availability: &Availability, parent: &Availability) -> Option<String> {
    let inherited = |platform: &str| {
        parent
            .platforms
            .iter()
            .find(|(name, _)| name == platform)
            .and_then(|(_, version)| version.as_ref())
    };
    let versions: Vec<String> = availability
        .platforms
        .iter()
        .filter_map(|(platform, version)| {
            let version = version.as_ref()?;
            (Some(version) != inherited(platform)).then(|| format!("{platform} {version}"))
        })
        .collect();
    (!versions.is_empty()).then(|| versions.join(", "))
}
