//! The Kotlin native plugin of an Android binding: one class that performs
//! each bound call, by type, and implements the module's interfaces and
//! abstract classes for JavaScript handlers.

use std::fmt::Write as _;

use super::android::kotlin_name;
use super::model::{
    Availability, Callback, Collection, Kind, Member, MemberKind, Module, NamedKind, Ty, Type,
};

/// The Kotlin package of the plugin `id`'s bindings, whose `Bindings` class
/// the Android pack registers.
pub(crate) fn package(id: &str) -> String {
    format!("com.tokamak.bindings.{}", id.replace('-', "_"))
}

pub(crate) fn emit(module: &Module, id: &str) -> String {
    let mut out = String::new();
    let _ = writeln!(
        out,
        "// Generated by `tok bindings` from {}. Do not edit.",
        module.source
    );
    // The bindings call deprecated APIs on purpose; the platform checks
    // permissions when they are called.
    out.push_str("@file:Suppress(\"DEPRECATION\", \"OVERRIDE_DEPRECATION\", \"UNCHECKED_CAST\")\n@file:SuppressLint(\"MissingPermission\")\n\n");
    let _ = writeln!(out, "package {}\n", package(id));
    for import in [
        "android.annotation.SuppressLint",
        "android.os.Build",
        "com.tokamak.runtime.TokamakBinding",
        "com.tokamak.runtime.TokamakHost",
        "com.tokamak.runtime.TokamakPlugin",
        "com.tokamak.runtime.TokamakPluginBytesReply",
        "com.tokamak.runtime.TokamakPluginError",
    ] {
        let _ = writeln!(out, "import {import}");
    }
    let _ = writeln!(
        out,
        "\nclass Bindings(private val host: TokamakHost) : TokamakPlugin {{\n    override val id = {}",
        literal(&module.plugin)
    );
    calls(&mut out, module);
    subscriptions(&mut out, module);
    for ty in module.types.iter().filter(|ty| !ty.members.is_empty()) {
        type_calls(&mut out, ty);
    }
    for ty in &module.types {
        if let Some(callbacks) = ty.callbacks() {
            implementation(&mut out, ty, callbacks);
        }
    }
    out.push_str("}\n");
    out
}

/// The name of the function that performs a type's calls.
fn function(ty: &Type) -> String {
    format!("call{}", ty.path.join("_"))
}

/// `text` as a Kotlin string literal, in which `$` would start a template.
fn literal(text: &str) -> String {
    format!(
        "\"{}\"",
        text.replace('\\', "\\\\")
            .replace('"', "\\\"")
            .replace('$', "\\$")
    )
}

/// The type's class without type arguments, as a class literal names it.
fn raw(native: &str) -> &str {
    native.split('<').next().unwrap_or(native)
}

/// The last branch of a request `when`: the rejection of a member the plugin does not bind.
const UNBOUND: &str = "            else -> throw TokamakPluginError.notSupported(\"$method is not supported\")";

fn calls(out: &mut String, module: &Module) {
    out.push_str(
        "\n    override fun callBytes(method: String, payload: ByteArray, reply: TokamakPluginBytesReply): (() -> Unit)? {\n        val b = TokamakBinding(payload, host.resources, reply)\n        return when (method.substringBefore('#')) {\n",
    );
    for ty in module.types.iter().filter(|ty| !ty.members.is_empty()) {
        let _ = writeln!(
            out,
            "            {} -> {}(method, b)",
            literal(&ty.name()),
            function(ty)
        );
    }
    let _ = writeln!(out, "{UNBOUND}\n        }}\n    }}");
}

fn subscriptions(out: &mut String, module: &Module) {
    out.push_str(
        "\n    override fun subscribeBytes(method: String, payload: ByteArray, reply: TokamakPluginBytesReply): () -> Unit {\n        val b = TokamakBinding(payload, host.resources, reply)\n        return when (method) {\n",
    );
    for ty in module.types.iter().filter(|ty| ty.callbacks().is_some()) {
        let guard = guard(&ty.availability, "\n                ");
        let _ = writeln!(
            out,
            "            {} -> {{\n                {guard}b.implement {{ {}Implementation(it) }}\n            }}",
            literal(&ty.name()),
            ty.path.join("_")
        );
    }
    let _ = writeln!(out, "{UNBOUND}\n        }}\n    }}");
}

/// The API level that introduced a symbol, when later than the first.
fn introduced(availability: &Availability) -> Option<&str> {
    availability
        .platforms
        .first()
        .and_then(|(_, level)| level.as_deref())
        .filter(|level| *level != "1")
}

/// The check, followed by `separator`, that rejects a call on API levels
/// before the symbol's.
fn guard(availability: &Availability, separator: &str) -> String {
    introduced(availability).map_or_else(String::new, |level| {
        format!("if (Build.VERSION.SDK_INT < {level}) throw TokamakBinding.unavailable{separator}")
    })
}

fn type_calls(out: &mut String, ty: &Type) {
    let _ = writeln!(
        out,
        "\n    private fun {}(method: String, b: TokamakBinding): (() -> Unit)? =\n        when (method) {{",
        function(ty)
    );
    for member in &ty.members {
        let guard = guard(&member.availability, "; ");
        let _ = writeln!(
            out,
            "            {} -> b.run {{ {guard}{} }}",
            literal(&member.key),
            body(ty, member)
        );
    }
    let _ = writeln!(out, "{UNBOUND}\n        }}");
}

/// The statements that perform `member` and return its encoded result.
fn body(owner: &Type, member: &Member) -> String {
    let class = raw(&owner.native);
    let target = if member.is_static {
        class.to_owned()
    } else if owner.native.contains('<') {
        format!("(b.target({class}::class.java) as {})", owner.native)
    } else {
        format!("b.target({class}::class.java)")
    };
    let name = kotlin_name(&member.native);
    let last = member.params.len().saturating_sub(1);
    let arguments: Vec<String> = member
        .params
        .iter()
        .enumerate()
        .map(|(index, param)| {
            let spread = if member.variadic && index == last {
                "*"
            } else {
                ""
            };
            format!("{spread}{}", decode(&param.ty, &format!("b[{index}]"), 1))
        })
        .collect();
    let arguments = arguments.join(", ");
    let call = match member.kind {
        MemberKind::Initializer => format!("{class}({arguments})"),
        MemberKind::Method => format!("{target}.{name}({arguments})"),
        MemberKind::Getter => format!("{target}.{name}"),
        MemberKind::Setter => format!("{target}.{name} = {arguments}"),
    };
    if member.result == Ty::Void {
        format!("{call}; null")
    } else {
        format!("b.encode({call})")
    }
}

/// The expression decoding the JSON `value` as `ty`, naming lambda
/// parameters by `depth`.
fn decode(ty: &Ty, value: &str, depth: usize) -> String {
    let parameter = format!("x{depth}");
    let inner = |ty: &Ty| decode(ty, &parameter, depth + 1);
    match ty {
        Ty::Bool => format!("b.boolean({value})"),
        Ty::Int(native) | Ty::Float(native) => format!(
            "b.{}({value})",
            native.trim_start_matches("java.lang.").to_lowercase()
        ),
        Ty::Char => format!("b.char({value})"),
        Ty::Bytes => format!("b.bytes({value})"),
        Ty::Optional(ty) => format!("b.optional({value}) {{ {parameter} -> {} }}", inner(ty)),
        Ty::List(element, collection) => {
            let list = format!("b.list({value}) {{ {parameter} -> {} }}", inner(element));
            match collection {
                Collection::Array => list,
                Collection::Set => format!("{list}.toSet()"),
                Collection::JavaArray => format!("{list}.{}", to_array(element)),
            }
        }
        Ty::Record(ty) => format!("b.map({value}) {{ {parameter} -> {} }}", inner(ty)),
        Ty::Named(named) => match &named.kind {
            NamedKind::Enum => format!("enumValueOf<{}>(b.string({value}))", raw(&named.native)),
            NamedKind::Alias(target) => decode(target, value, depth),
            _ if named.native.contains('<') => format!(
                "(b.obj({value}, {}::class.java) as {})",
                raw(&named.native),
                named.native
            ),
            _ => format!("b.obj({value}, {}::class.java)", named.native),
        },
        Ty::Any => format!("b.any({value})"),
        _ => format!("b.string({value})"),
    }
}

/// The conversion of a decoded list to the Java array of `element`.
fn to_array(element: &Ty) -> &'static str {
    match element {
        Ty::Bool => "toBooleanArray()",
        Ty::Int(native) if native == "byte" => "toByteArray()",
        Ty::Int(native) if native == "short" => "toShortArray()",
        Ty::Int(native) if native == "long" => "toLongArray()",
        Ty::Int(_) => "toIntArray()",
        Ty::Float(native) if native == "float" => "toFloatArray()",
        Ty::Float(_) => "toDoubleArray()",
        Ty::Char => "toCharArray()",
        _ => "toTypedArray()",
    }
}

/// The class that implements an interface, or extends an abstract class, for JavaScript handlers.
fn implementation(out: &mut String, ty: &Type, callbacks: &[Callback]) {
    let constructor = if matches!(ty.kind, Kind::Class { .. }) {
        "()"
    } else {
        ""
    };
    // Lint then checks that each construction is guarded.
    let requires = introduced(&ty.availability).map_or_else(String::new, |level| {
        format!("\n    @androidx.annotation.RequiresApi({level})")
    });
    let _ = writeln!(
        out,
        "{requires}\n    private class {}Implementation(private val binding: TokamakBinding) : {}{constructor} {{",
        ty.path.join("_"),
        ty.native
    );
    for (position, method) in callbacks.iter().enumerate() {
        if position > 0 {
            out.push('\n');
        }
        let arguments: Vec<String> = method
            .params
            .iter()
            .map(|param| format!("b.encode({})", kotlin_name(&param.name)))
            .collect();
        let call = format!(
            "binding.call({}) {{ b -> listOf({}) }}",
            literal(&method.name),
            arguments.join(", ")
        );
        let body = if method.default {
            let names: Vec<String> = method
                .params
                .iter()
                .map(|param| kotlin_name(&param.name))
                .collect();
            format!(
                "if (!{call}) super.{}({})",
                kotlin_name(&method.name),
                names.join(", ")
            )
        } else {
            call
        };
        let _ = writeln!(
            out,
            "        {} {{\n            {body}\n        }}",
            method.declaration
        );
    }
    out.push_str("    }\n");
}
