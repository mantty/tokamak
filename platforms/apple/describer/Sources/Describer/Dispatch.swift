/// The Swift extension of `plugin` that routes the Worker's requests to the
/// exported `methods`, and encodes the registered `events` and decodes their
/// replies, and the coding of the `unions` of the described `types`,
/// formatted as swift-format formats it.
func dispatch(
  plugin: String, methods: [PlatformExport], events: [PlatformEvent], platforms: [String],
  types: [String: NamedType], unions: [String: PlatformUnion]
) -> String {
  let takesBody = { (method: PlatformExport) in method.export.parameters.last?.type == .body }
  let calls = methods.filter { $0.export.registration.kind == .call }
  let requests = { (methods: [PlatformExport]) in
    methods.map { method in
      Case(
        name: method.export.registration.name, platforms: method.platforms,
        body: caseBody(method.export))
    }
  }
  let unsupported = { (reason: String) in "throw .notSupported(\"\\(id).\\(method) \(reason)\")" }
  let functions = [
    function(
      [
        "func callBytes(method: String, payload: Data, reply: @escaping TokamakPluginBytesReply)",
        "  throws(TokamakPluginError) -> (() -> Void)?",
        "{",
      ], switching: "method", requests(calls.filter { !takesBody($0) }),
      otherwise: unsupported("is not supported"), platforms),
    function(
      [
        "func callBytes(",
        "  method: String, payload: Data, body: TokamakPluginBody,",
        "  reply: @escaping TokamakPluginBytesReply",
        ") throws(TokamakPluginError) -> (() -> Void)? {",
      ], switching: "method", requests(calls.filter(takesBody)),
      otherwise: unsupported("does not take a body"), platforms),
    function(
      [
        "func subscribeBytes(method: String, payload: Data, reply: @escaping TokamakPluginBytesReply)",
        "  throws(TokamakPluginError) -> (() -> Void)",
        "{",
      ], switching: "method", requests(methods.filter { $0.export.registration.kind != .call }),
      otherwise: unsupported("is not supported"), platforms),
    function(
      ["func eventPayload(_ name: String, _ event: Any) throws(TokamakPluginError) -> Data {"],
      switching: "name",
      events.map { event in
        let registration = event.event.registration
        return Case(
          name: registration.name, platforms: event.platforms,
          body: ["return try tokamakEvent(name, event, as: \(registration.type).self)"])
      }, otherwise: "throw .unlistedEvent(name)", platforms),
    function(
      ["func eventReply(_ name: String, _ reply: Data) throws(TokamakPluginError) -> Any? {"],
      switching: "name",
      events.compactMap { event in
        let registration = event.event.registration
        return registration.reply.map { type in
          Case(
            name: registration.name, platforms: event.platforms,
            body: ["return try tokamakDecode(\(type)?.self, from: reply, in: \"reply\")"])
        }
      }, otherwise: "throw .unlistedReply(name)", platforms),
  ].filter { !$0.isEmpty }
  let codings = unions.sorted { $0.key < $1.key }.flatMap { name, union in
    let lines = coding(types[name]!, union.coding, types: types)
    guard union.platforms != platforms else { return [""] + lines }
    return ["", condition(union.platforms)] + indented(lines) + ["#endif"]
  }
  let lines =
    ["// Generated by `tok plugin generate apple`. Do not edit.", "", "import Foundation", ""]
    + ["extension \(plugin) {"] + functions.joined(separator: [""]) + ["}"] + codings
  return lines.joined(separator: "\n") + "\n"
}

/// The `Codable` conformance of the union `type`, which chooses a case by the value's tag, or
/// else by its JSON: its kind, a string's value, and a key only one struct case's objects have.
private func coding(
  _ type: NamedType, _ coding: UnionCoding, types: [String: NamedType]
) -> [String] {
  let alternatives = type.alternatives ?? []
  let structs = alternatives.compactMap { alternative -> [Field]? in
    guard case .named(let name)? = alternative.type else { return nil }
    return types[name]?.fields
  }
  var decode: [String] = []
  var encode: [String] = []
  for alternative in alternatives {
    let name = alternative.name
    let payload = coding.payloads[name]
    let matched =
      type.tag == nil ? pattern(alternative, types: types, structs: structs) : "\"\(name)\""
    let decoded = payload.map { "(try value.decode(\($0).self))" } ?? ""
    decode += ["case \(matched):", "  self = .\(name)\(decoded)"]
    let value = payload == nil ? "" : "value"
    let encoded =
      type.tag.map {
        "tokamakEncode(tag: \"\($0)\", \"\(name)\"\(value.isEmpty ? "" : ", value"), to: encoder)"
      }
      ?? "container.encode(\(value.isEmpty ? "\"\(name)\"" : value))"
    encode += ["case .\(name)\(value.isEmpty ? "" : "(let value)"):", "  try \(encoded)"]
  }
  let subject = type.tag.map { "try value.tag(\"\($0)\")" } ?? "value.kind"
  let container = type.tag == nil ? ["    var container = encoder.singleValueContainer()"] : []
  return ["extension \(coding.path) {", "  init(from decoder: any Decoder) throws {"]
    + ["    let value = try TokamakUnionValue(decoder)", "    switch \(subject) {"]
    + decode.map { "    \($0)" }
    + ["    default:", "      throw value.mismatch(\"\(type.name)\")", "    }", "  }", ""]
    + ["  func encode(to encoder: any Encoder) throws {"] + container + ["    switch self {"]
    + encode.map { "    \($0)" } + ["    }", "  }", "}"]
}

/// The pattern of `value.kind` that the JSON of `alternative` matches: its name, or its value.
private func pattern(
  _ alternative: Alternative, types: [String: NamedType], structs: [[Field]]
) -> String {
  switch alternative.type {
  case nil: return ".string(\"\(alternative.name)\")"
  case .string: return ".string"
  case .number: return ".number"
  case .boolean: return ".boolean"
  case .array: return ".array"
  case .named(let name) where types[name]?.values != nil:
    let values = (types[name]?.values ?? []).map { "\"\($0)\"" }.joined(separator: ", ")
    return ".string(let string) where [\(values)].contains(string)"
  case .named(let name) where structs.count > 1:
    let fields = types[name]?.fields ?? []
    let others = structs.filter { $0 != fields }.flatMap { $0 }
    let key = fields.first { field in
      !field.type.isOptional && !others.contains { $0.name == field.name }
    }
    return ".object(let keys) where keys.contains(\"\(key?.name ?? "")\")"
  default: return ".object"
  }
}

/// One case of a function's switch: a method or event, which only some of the
/// family's platforms may have.
private struct Case {
  let name: String
  let platforms: [String]
  let body: [String]
}

/// A function that switches on `subject`, running `otherwise` for anything
/// but the `cases`, or nothing without cases.
private func function(
  _ signature: [String], switching subject: String, _ cases: [Case], otherwise: String,
  _ platforms: [String]
) -> [String] {
  guard !cases.isEmpty else { return [] }
  var lines = signature.map { "  \($0)" } + ["    switch \(subject) {"]
  for item in cases {
    let body = ["case \"\(item.name)\":"] + indented(item.body)
    if item.platforms == platforms {
      lines += body.map { "    \($0)" }
    } else {
      lines += ["    \(condition(item.platforms))"] + body.map { "      \($0)" } + ["    #endif"]
    }
  }
  return lines + ["    default:", "      \(otherwise)", "    }", "  }"]
}

/// Decodes the method's arguments, calls it, and replies.
private func caseBody(_ export: Export) -> [String] {
  let decoded = export.parameters.filter { ![.body, .bytes].contains($0.type) }
  var lines: [String] = []
  if !decoded.isEmpty {
    let resources = decoded.contains { $0.type == .reference } ? ", resources: host.resources" : ""
    lines += ["struct Arguments: Decodable {"]
    lines += decoded.map { "  let \($0.name): \($0.spelling)" }
    lines += ["}", "let arguments = try tokamakDecode(Arguments.self, from: payload\(resources))"]
  }
  let arguments = export.parameters.map { parameter in
    let label = parameter.label == "_" ? "" : "\(parameter.label): "
    switch parameter.type {
    case .body: return label + "body"
    case .bytes: return label + "payload"
    default: return label + "arguments.\(parameter.name)"
    }
  }
  let effects = (export.throwing ? "try " : "") + (export.awaited ? "await " : "")
  let call = wrapped(
    "\(effects)self.\(export.registration.name)(", arguments, ")", indent: 8)
  let synchronous = export.awaited ? "" : "try "
  let reply =
    switch export.registration.kind {
    case .call: "return tokamakCall(reply) {"
    case .stream: "return \(synchronous)tokamakStream(reply) {"
    case .resource: "return \(synchronous)tokamakResource(host.resources, reply) {"
    }
  return lines + [reply] + call.map { "  \($0)" } + ["}"]
}

/// `open`, the comma-separated `items` and `close` on one line within 100
/// columns at `indent`, or with the items on following lines.
private func wrapped(_ open: String, _ items: [String], _ close: String, indent: Int) -> [String] {
  let line = open + items.joined(separator: ", ") + close
  if indent + line.count <= 100 { return [line] }
  let continuation = items.joined(separator: ", ") + close
  if indent + 2 + continuation.count <= 100 { return [open, "  " + continuation] }
  return [open]
    + items.enumerated().map { index, item in
      "  " + item + (index == items.count - 1 ? close : ",")
    }
}

/// The `#if` that compiles what follows on `platforms`, iOS or macOS.
private func condition(_ platforms: [String]) -> String {
  "#if " + platforms.map { $0 == "ios" ? "os(iOS)" : "os(macOS)" }.joined(separator: " || ")
}

private func indented(_ lines: [String]) -> [String] {
  lines.map { "  \($0)" }
}
