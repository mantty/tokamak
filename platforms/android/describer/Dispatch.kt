package com.tokamak.runtime

import kotlin.reflect.KClass
import kotlin.reflect.KType
import kotlin.reflect.full.findAnnotation
import kotlin.reflect.full.starProjectedType
import kotlin.reflect.full.withNullability
import org.json.JSONArray
import org.json.JSONObject

/**
 * The Kotlin dispatch of [plugin]'s [exports] and [events]: the `<Plugin>Dispatch` class the app's
 * registry creates, with a decoder and an encoder of each data class and sealed type they use.
 */
internal fun dispatch(plugin: KClass<*>, exports: List<Export>, events: List<Event>): String {
    val code = Code(plugin.java.packageName)
    val takesBody = { export: Export -> export.parameters.lastOrNull()?.type?.classifier == TokamakPluginBody::class }
    val calls = exports.filter { it.kind == "call" }
    val requests = listOf(
        code.function(
            "override fun callBytes(method: String, payload: ByteArray, reply: TokamakPluginBytesReply): (() -> Unit)? {",
            calls.filterNot(takesBody),
            "is not supported",
        ),
        code.function(
            "override fun callBytes(method: String, payload: ByteArray, body: TokamakPluginBody, reply: TokamakPluginBytesReply): (() -> Unit)? {",
            calls.filter(takesBody),
            "does not take a body",
        ),
        code.function(
            "override fun subscribeBytes(method: String, payload: ByteArray, reply: TokamakPluginBytesReply): () -> Unit {",
            exports.filter { it.kind != "call" },
            "is not supported",
        ),
    )
    val results = exports.filter { it.kind != "resource" }.map { if (it.kind == "stream") it.returns.arguments.single().type!! else it.returns }
    val parameters = exports.flatMap { export -> export.parameters.map { it.type } }
    val classes = jsonClasses(parameters + results + events.flatMap { listOfNotNull(it.type, it.reply) })
    val functions = requests.filter { it.isNotEmpty() }
    val name = code.name(plugin)
    // Conversions are the companion's, so the file declares only the class, whose name is the plugin's.
    val dispatch = listOf(
        "/** Routes the Worker's requests to the methods [$name] exports. */",
        "class ${name}Dispatch(host: TokamakHost) : TokamakDispatch<$name>($name(host), host) {",
    ) + functions.flatMap { listOf("") + it }.drop(1) + code.codec(name, classes, events) + "}"
    val header = listOf("// Generated by `tok plugin generate android`. Do not edit.", "package ${code.packageName}", "")
    return (header + code.imports() + "" + dispatch).joinToString("\n") + "\n"
}

/** Kotlin generated in [packageName], and the imports it uses. */
private class Code(val packageName: String) {
    private val imports = sortedSetOf(
        "com.tokamak.runtime.TokamakDispatch",
        "com.tokamak.runtime.TokamakHost",
        "com.tokamak.runtime.TokamakPluginBytesReply",
        "com.tokamak.runtime.TokamakPluginError",
    )

    fun imports(): List<String> = imports.map { "import $it" }

    /** [type]'s name in the generated code: without its package in Kotlin's or the plugin's. */
    fun name(type: KClass<*>): String {
        val qualified = type.qualifiedName ?: throw DescribeError("$type has no name")
        return when {
            qualified.startsWith("kotlin.") -> qualified.substringAfterLast('.')
            type.java.packageName == packageName -> qualified.removePrefix("$packageName.")
            else -> qualified
        }
    }

    /** A request function that switches on the method, or nothing without methods. */
    fun function(signature: String, exports: List<Export>, unsupported: String): List<String> {
        if (exports.isEmpty()) return emptyList()
        if ("TokamakPluginBody" in signature) imports += "com.tokamak.runtime.TokamakPluginBody"
        val decodes = exports.any { export -> export.parameters.any { it.type.classifier !in RAW } }
        // Only the request's serial executor reads the arguments.
        val arguments = if (decodes) listOf("        val arguments by lazy(LazyThreadSafetyMode.NONE) { TokamakValue.arguments(payload) }") else emptyList()
        if (decodes) imports += "com.tokamak.runtime.TokamakValue"
        return listOf("    $signature") + arguments + "        return when (method) {" +
            exports.flatMap { branch(it) }.map { "            $it" } +
            "            else -> throw TokamakPluginError.notSupported(\"\$id.\$method $unsupported\")" +
            "        }" + "    }"
    }

    /** The encoding of the events' payloads, or nothing without events. */
    private fun events(events: List<Event>): List<String> {
        if (events.isEmpty()) return emptyList()
        val branches = events.map { event ->
            val type = event.type.classifier as KClass<*>
            "\"${event.name}\" -> encodeEvent(name, event, ${name(type)}::class) { ${encode(event.type, "it")} }"
        }
        return switch("override fun eventPayload(name: String, event: Any): ByteArray =", branches, "super.eventPayload(name, event)")
    }

    /** The decoding of the events' replies, or nothing when no event takes one. */
    private fun replies(events: List<Event>): List<String> {
        val branches = events.mapNotNull { event -> event.reply?.let { "\"${event.name}\" -> ${decode(it, "reply")}" } }
        if (branches.isEmpty()) return emptyList()
        imports += "com.tokamak.runtime.TokamakValue"
        return switch("override fun eventReply(name: String, reply: TokamakValue): Any =", branches, "super.eventReply(name, reply)")
    }

    /**
     * The companion object that converts the [classes] and [events] to and from JSON, for the
     * dispatch's methods and the plugin's host. A sealed type's data class form encodes as the
     * sealed type does, with its tag.
     */
    fun codec(plugin: String, classes: Set<KClass<*>>, events: List<Event>): List<String> {
        imports += "com.tokamak.runtime.TokamakCodec"
        val doc = "    /** Converts the values and events of [$plugin] to and from JSON. */"
        val sorted = classes.sortedBy { it.simpleName }
        val switches = listOf(events(events), replies(events), values(sorted)).filter { it.isNotEmpty() }
        if (switches.isEmpty()) return listOf("", doc, "    companion object : TokamakCodec")
        val members = switches.flatMap { listOf("") + it }.drop(1).map { if (it.isEmpty()) it else "    $it" }
        val conversions = sorted.flatMap { decoder(it) + encoder(it) }
        return listOf("", doc, "    companion object : TokamakCodec {") + members +
            conversions.map { if (it.isEmpty()) it else "        $it" } + "    }"
    }

    /** The conversions of the [classes], sorted by name, to and from JSON by type, or nothing without classes. */
    private fun values(classes: List<KClass<*>>): List<String> {
        if (classes.isEmpty()) return emptyList()
        imports += listOf("com.tokamak.runtime.TokamakValue", "kotlin.reflect.KClass")
        val forms = classes.filter { it.isSealed }.flatMap { forms(it).map(Form::type) }.toSet()
        val encodes = classes.filter { it !in forms }.map { "is ${name(it)} -> json(value)" }
        val decodes = classes.map { "${name(it)}::class -> json.as${it.simpleName}()" }
        return switch("override fun encodeValue(value: Any): Any =", "value", encodes, "super.encodeValue(value)") + "" +
            switch("override fun decodeValue(json: TokamakValue, type: KClass<*>): Any =", "type", decodes, "super.decodeValue(json, type)")
    }

    /** A function whose body switches on the event's name, leaving others to [otherwise]. */
    private fun switch(signature: String, branches: List<String>, otherwise: String): List<String> = switch(signature, "name", branches, otherwise)

    private fun switch(signature: String, subject: String, branches: List<String>, otherwise: String): List<String> =
        listOf("    $signature", "        when ($subject) {") + branches.map { "            $it" } +
            "            else -> $otherwise" + "        }"

    /** Calls the export with its decoded arguments, and replies. */
    private fun branch(export: Export): List<String> {
        val label = "\"${export.name}\" ->"
        val call = call(export)
        return when {
            export.kind == "call" -> {
                val start = if (export.suspends) "launch(method, reply)" else "respond(reply)"
                lambda(label, start, call) { encode(export.returns, it) }
            }
            export.kind == "stream" -> {
                val encoded = encode(export.returns.arguments.single().type!!, "it")
                val each = if (encoded == "it") "" else " { $encoded }"
                use(label, call) { "collect(method, reply, $it)$each" }
            }
            export.suspends -> lambda(label, "retain(method, reply)", call) { it }
            else -> use(label, call) { "retain(reply, $it)" }
        }
    }

    /** `start { call }`, replying with the call's result as [encode] encodes it. */
    private fun lambda(label: String, start: String, call: List<String>, encode: (String) -> String): List<String> =
        when {
            call.size == 1 -> listOf("$label $start { ${encode(call.single())} }")
            encode("result") == "result" -> listOf("$label $start {") + call.map { "    $it" } + "}"
            else -> listOf("$label $start {", "    val result = ${call.first()}") + call.drop(1).map { "    $it" } + "    ${encode("result")}" + "}"
        }

    /** What [use] makes of the call's result, called on the request's executor. */
    private fun use(label: String, call: List<String>, use: (String) -> String): List<String> =
        if (call.size == 1) {
            listOf("$label ${use(call.single())}")
        } else {
            listOf("$label {", "    val result = ${call.first()}") + call.drop(1).map { "    $it" } + "    ${use("result")}" + "}"
        }

    /** The plugin method's call: on one line when it is short, and otherwise one argument per line. */
    private fun call(export: Export): List<String> {
        val arguments = export.parameters.map { parameter ->
            val value = when (parameter.type.classifier) {
                TokamakPluginBody::class -> "body"
                ByteArray::class -> "payload"
                else -> decode(parameter.type, "arguments[\"${parameter.name}\"]")
            }
            "${parameter.name} = $value"
        }
        val line = "plugin.${export.name}(${arguments.joinToString()})"
        return if (line.length <= 60) listOf(line) else listOf("plugin.${export.name}(") + arguments.map { "    $it," } + ")"
    }

    /** Reads [type] from the JSON value [value]. */
    fun decode(type: KType, value: String): String {
        if (type.isMarkedNullable) return "$value.nullable { ${decode(type.withNullability(false), "it")} }"
        val classifier = type.classifier as KClass<*>
        val argument = { index: Int -> type.arguments[index].type!! }
        return when (classifier) {
            String::class -> "$value.string()"
            Boolean::class -> "$value.boolean()"
            Int::class -> "$value.int()"
            Long::class -> "$value.long()"
            Short::class -> "$value.short()"
            Byte::class -> "$value.byte()"
            Double::class -> "$value.double()"
            Float::class -> "$value.float()"
            Any::class -> "$value.any()"
            JSONObject::class -> "$value.jsonObject()"
            JSONArray::class -> "$value.jsonArray()"
            List::class -> "$value.list { ${decode(argument(0), "it")} }"
            Map::class -> "$value.map { ${decode(argument(1), "it")} }"
            TokamakReference::class -> "$value.reference(host.resources, ${name(argument(0).classifier as KClass<*>)}::class.java)"
            else -> if (classifier.java.isEnum) "$value.enum(${name(classifier)}.entries)" else "$value.as${classifier.simpleName}()"
        }
    }

    /** [value] of [type] as JSON: itself when it is a string, boolean, number, bytes or nothing. */
    fun encode(type: KType, value: String): String {
        if (type.classifier in SCALARS) return value
        val classifier = type.classifier as KClass<*>
        if (type.isMarkedNullable) {
            return "$value?.let { ${encode(type.withNullability(false), "it")} }"
        }
        return when {
            classifier == List::class -> {
                imports += "org.json.JSONArray"
                val element = encode(type.arguments[0].type!!, "it")
                if (element == "it") "JSONArray($value)" else "JSONArray($value.map { $element })"
            }
            classifier == Map::class -> {
                imports += "org.json.JSONObject"
                val entry = encode(type.arguments[1].type!!, "it.value")
                if (entry == "it.value") "JSONObject($value)" else "JSONObject($value.mapValues { $entry })"
            }
            classifier.java.isEnum -> {
                imports += "com.tokamak.runtime.jsonName"
                "jsonName($value.name)"
            }
            else -> "json($value)"
        }
    }

    /** The decoder of the data class or sealed type [type]. */
    fun decoder(type: KClass<*>): List<String> {
        val name = name(type)
        if (type.isSealed) return formDecoder(type)
        return listOf("", "private fun TokamakValue.as${type.simpleName}(): $name =", "    $name(") +
            fields(type).map { "        ${it.name} = ${decode(it.type, "this[\"${it.name}\"]")}," } + "    )"
    }

    /** The encoder of the data class or sealed type [type]. */
    fun encoder(type: KClass<*>): List<String> {
        if (type.isSealed) return formEncoder(type)
        imports += "org.json.JSONObject"
        return listOf("", "private fun json(value: ${name(type)}): JSONObject =", "    JSONObject()") +
            fields(type).map { field ->
                val put = if (field.type.isMarkedNullable) "putOpt" else "put"
                "        .$put(\"${field.name}\", ${encode(field.type, "value.${field.name}")})"
            }
    }

    /**
     * The decoder of the sealed type [type], which chooses a form by the value's tag, or else by its
     * JSON: its kind, a string's value, and a key only one data class form's objects have.
     */
    private fun formDecoder(type: KClass<*>): List<String> {
        val forms = forms(type)
        val tag = type.findAnnotation<TokamakTag>()?.field
        val objects = forms.filter { !it.isName && it.value == null }
        val branches = forms.map { form ->
            val value = form.value
            val decoded = when {
                form.isName -> name(form.type)
                value != null -> "${name(form.type)}(${decode(value.type, "this")})"
                else -> "as${form.type.simpleName}()"
            }
            val condition = when {
                tag != null -> "\"${form.name}\""
                form.isName -> "json == \"${form.name}\""
                value != null -> kind(value.type)
                objects.size > 1 -> "${isObject()} && json.has(\"${key(form, objects)}\")"
                else -> isObject()
            }
            "$condition -> $decoded"
        }
        val signature = "private fun TokamakValue.as${type.simpleName}(): ${name(type)}"
        val mismatch = "else -> throw mismatch(\"${type.simpleName}\")"
        if (tag != null) {
            return listOf("", "$signature =", "    when (this[\"$tag\"].string()) {") + branches.map { "        $it" } + "        $mismatch" + "    }"
        }
        return listOf("", "$signature {", "    val json = json()", "    return when {") + branches.map { "        $it" } + "        $mismatch" + "    }" + "}"
    }

    /** The condition that the JSON `json` is an object. */
    private fun isObject(): String {
        imports += "org.json.JSONObject"
        return "json is JSONObject"
    }

    /** The condition that the JSON `json` is a value class form's value of [type]. */
    private fun kind(type: KType): String {
        val classifier = type.classifier as KClass<*>
        return when {
            classifier == String::class -> "json is String"
            classifier == Boolean::class -> "json is Boolean"
            classifier in NUMBERS -> "json is Number"
            classifier.java.isEnum -> {
                val values = constants(classifier).joinToString { "\"$it\"" }
                "json is String && json in setOf($values)"
            }
            classifier == List::class || classifier == JSONArray::class -> {
                imports += "org.json.JSONArray"
                "json is JSONArray"
            }
            // A map or JSONObject: a value class holds no data class, which is a form itself.
            else -> isObject()
        }
    }

    /** The encoder of the sealed type [type]: each form's name, value, or data class, with its tag. */
    private fun formEncoder(type: KClass<*>): List<String> {
        val tag = type.findAnnotation<TokamakTag>()?.field
        if (tag != null) imports += "org.json.JSONObject"
        val tagged = { form: Form -> tag?.let { ".put(\"$it\", \"${form.name}\")" } ?: "" }
        val branches = forms(type).map { form ->
            val value = form.value
            when {
                form.isName && tag != null -> "${name(form.type)} -> JSONObject()${tagged(form)}"
                form.isName -> "${name(form.type)} -> \"${form.name}\""
                value != null -> "is ${name(form.type)} -> ${encode(value.type, "value.${value.name}")}"
                else -> "is ${name(form.type)} -> json(value)${tagged(form)}"
            }
        }
        val returns = if (tag != null) "JSONObject" else "Any"
        return listOf("", "private fun json(value: ${name(type)}): $returns =", "    when (value) {") + branches.map { "        $it" } + "    }"
    }
}

/** The first required field of the data class [form] that none of the other [objects] has. */
private fun key(form: Form, objects: List<Form>): String {
    val others = objects.filter { it != form }.flatMap { fields(it.type) }.map { it.name }.toSet()
    return fields(form.type).firstOrNull { !it.type.isMarkedNullable && it.name !in others }?.name.orEmpty()
}

/** The data classes and sealed types [types] use, directly, through fields, or as forms, which convert to and from JSON. */
private fun jsonClasses(types: List<KType>): Set<KClass<*>> {
    val found = mutableSetOf<KClass<*>>()
    fun visit(type: KType) {
        type.arguments.forEach { argument -> argument.type?.let(::visit) }
        val classifier = type.classifier as? KClass<*> ?: return
        if (classifier.isSealed && found.add(classifier)) {
            for (form in forms(classifier)) visit(form.value?.type ?: form.type.starProjectedType)
        }
        if (classifier.isData && classifier.objectInstance == null && found.add(classifier)) fields(classifier).forEach { visit(it.type) }
    }
    types.forEach(::visit)
    return found
}

/** Parameters the request carries apart from its JSON arguments. */
private val RAW = setOf(TokamakPluginBody::class, ByteArray::class)

/** Kotlin's numeric types, which are JSON numbers. */
private val NUMBERS = setOf(Int::class, Long::class, Short::class, Byte::class, Double::class, Float::class)

/** The types whose values are JSON, or bytes, as they are. */
private val SCALARS = setOf(
    String::class, Boolean::class, Int::class, Long::class, Short::class, Byte::class, Double::class, Float::class, Unit::class, ByteArray::class,
    Any::class, JSONObject::class, JSONArray::class,
)
