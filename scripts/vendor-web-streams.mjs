#!/usr/bin/env node
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, writeFileSync, rmSync } from "node:fs";
import { createRequire } from "node:module";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const version = "4.3.0";
const temporary = mkdtempSync(path.join(tmpdir(), "tokamak-web-streams-"));
const output = new URL("../tokamak/src/streams/", import.meta.url);
try {
  execFileSync("npm", ["install", "--prefix", temporary, "--cache", path.join(temporary, "cache"),
    "--ignore-scripts", "--no-audit", "--no-fund", `web-streams-polyfill@${version}`, "esbuild@0.25.9"], { stdio: "inherit" });
  const require = createRequire(path.join(temporary, "package.json"));
  const { transform } = require("esbuild");
  const source = readFileSync(path.join(temporary, "node_modules/web-streams-polyfill/dist/ponyfill.mjs"), "utf8");
  const { code } = await transform(source, { format: "esm", target: "es2022", legalComments: "inline" });
  const generated = path.join(temporary, "web-standard.mjs");
  writeFileSync(generated, `// Generated by scripts/vendor-web-streams.mjs from web-streams-polyfill@${version}.\n${code}`);
  execFileSync("git", ["apply", "-p0", fileURLToPath(new URL("web-streams-workerd.patch", import.meta.url))], { cwd: temporary });
  let branded = readFileSync(generated, "utf8");
  const types = ["ReadableStream", "WritableStream", "TransformStream", "ReadableStreamDefaultReader", "ReadableStreamBYOBReader",
    "ReadableStreamBYOBRequest", "ReadableByteStreamController", "ReadableStreamDefaultController", "WritableStreamDefaultController",
    "WritableStreamDefaultWriter", "TransformStreamDefaultController", "ByteLengthQueuingStrategy", "CountQueuingStrategy"];
  for (const type of types) {
    const constructor = new RegExp(`(class ${type} \\{\\n  constructor\\([^\\n]*\\) \\{\\n)`);
    if (!constructor.test(branded)) throw new Error(`Missing stream constructor: ${type}`);
    branded = branded.replace(constructor, "$1    markHostObject(this);\n");
    branded = branded.replaceAll(`Object.create(${type}.prototype)`, `markHostObject(Object.create(${type}.prototype))`);
  }
  branded = 'import { markHostObject } from "../globals/objects.mjs";\n' + branded;
  writeFileSync(new URL("web-standard.mjs", output), branded);
  writeFileSync(new URL("WEB-STREAMS-LICENSE", output), readFileSync(path.join(temporary, "node_modules/web-streams-polyfill/LICENSE")));
} finally {
  rmSync(temporary, { recursive: true, force: true });
}
