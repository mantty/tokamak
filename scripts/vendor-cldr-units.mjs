#!/usr/bin/env node
// Generates compressed unit patterns from Unicode CLDR.
import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { mkdtempSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { gzipSync } from "node:zlib";

const VERSION = "48.2.0";
const output = join(import.meta.dirname, "../tokamak/src/globals/intl");
const temporary = mkdtempSync(join(tmpdir(), "tokamak-cldr-"));
const rustNumber = value => String(value).replace(/\B(?=(\d{3})+(?!\d))/g, "_");
try {
  execFileSync("npm", ["install", "--prefix", temporary, "--cache", join(temporary, "cache"), "--ignore-scripts", "--no-audit", "--no-fund", `cldr-units-full@${VERSION}`], { stdio: "inherit" });
  const packageRoot = join(temporary, "node_modules/cldr-units-full");
  const blobs = [];
  const index = [];
  const shared = new Map();
  let offset = 0;
  for (const locale of readdirSync(join(packageRoot, "main")).sort()) {
    const source = JSON.parse(readFileSync(join(packageRoot, "main", locale, "units.json"), "utf8")).main[locale].units;
    const patterns = {};
    for (const width of ["long", "short", "narrow"]) {
      const units = { per: { other: source[width].per.compoundUnitPattern } };
      for (const [name, data] of Object.entries(source[width])) {
        if (!data["unitPattern-count-other"]) continue;
        const unit = name.slice(name.indexOf("-") + 1);
        assert.ok(!(unit in units), `Duplicate unit ${locale}/${width}/${unit}`);
        units[unit] = Object.fromEntries(Object.entries(data).flatMap(([key, value]) => {
          if (key.startsWith("unitPattern-count-")) return [[key.slice("unitPattern-count-".length), value]];
          if (key === "perUnitPattern") return [["per", value]];
          return [];
        }));
      }
      patterns[width] = units;
    }
    const json = JSON.stringify(patterns);
    const existing = shared.get(json);
    if (existing) {
      index.push(`    (${JSON.stringify(locale)}, ${rustNumber(existing.offset)}, ${rustNumber(existing.length)}),`);
      continue;
    }
    const bytes = gzipSync(json, { level: 9 });
    shared.set(json, { offset, length: bytes.length });
    index.push(`    (${JSON.stringify(locale)}, ${rustNumber(offset)}, ${rustNumber(bytes.length)}),`);
    blobs.push(bytes);
    offset += bytes.length;
  }
  mkdirSync(output, { recursive: true });
  writeFileSync(join(output, "units_data.bin"), Buffer.concat(blobs));
  writeFileSync(join(output, "units_data.rs"), `// Generated by scripts/vendor-cldr-units.mjs from CLDR ${VERSION}.\nconst DATA: &[u8] = include_bytes!("units_data.bin");\nconst LOCALES: &[(&str, usize, usize)] = &[\n${index.join("\n")}\n];\n`);
  writeFileSync(join(output, "CLDR-LICENSE"), readFileSync(join(packageRoot, "LICENSE")));
  const supplemental = JSON.parse(readFileSync(join(temporary, "node_modules/cldr-core/supplemental/plurals.json"), "utf8")).supplemental;
  const pluralLocales = Object.keys(supplemental["plurals-type-cardinal"]).sort();
  writeFileSync(join(output, "plurals_data.rs"), `// Generated by scripts/vendor-cldr-units.mjs from CLDR ${VERSION}.\nconst PLURAL_LOCALES: &[&str] = &[\n${pluralLocales.map(locale => `    ${JSON.stringify(locale)},`).join("\n")}\n];\n`);
  console.log(`Generated ${index.length} locales (${offset} compressed bytes)`);
} finally {
  rmSync(temporary, { recursive: true, force: true });
}
